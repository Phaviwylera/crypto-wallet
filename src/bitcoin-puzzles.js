export const BITCOIN_PUZZLES = Object.freeze(ROWS.map(([id, address, status, publicKey]) => Object.freeze({
  id, address, status, publicKey,
  lower: (1n << BigInt(id - 1)).toString(),
  upper: ((1n << BigInt(id)) - 1n).toString(),
})));

const BY_ADDRESS = new Map(BITCOIN_PUZZLES.map((puzzle) => [puzzle.address, puzzle]));

export function getBitcoinPuzzle(id) {
  const number = Number(id);
  if (!Number.isInteger(number) || number < 1 || number > BITCOIN_PUZZLES.length) throw new Error('Choose a Bitcoin puzzle from 1 through 160.');
  return BITCOIN_PUZZLES[number - 1];
}

export function getBitcoinPuzzleByAddress(address) {
  return BY_ADDRESS.get(address) ?? null;
}

export function bitcoinPuzzleCatalogTsv() {
  const header = 'puzzle\taddress\tsource_status\tlower_scalar_decimal\tupper_scalar_decimal\tpublished_public_key_compressed';
  const rows = BITCOIN_PUZZLES.map((p) => [p.id, p.address, p.status, p.lower, p.upper, p.publicKey ?? ''].join('\t'));
  const metadata = '# ' + BITCOIN_PUZZLE_SOURCE.name + '\n# Source commit ' + BITCOIN_PUZZLE_SOURCE.commit + ' (' + BITCOIN_PUZZLE_SOURCE.commitDate + '); retrieved ' + BITCOIN_PUZZLE_SOURCE.retrievedDate + '. Not live status or balance data.\n';
  return metadata + [header, ...rows].join('\n') + '\n';
}
