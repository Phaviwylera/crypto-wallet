import test from 'node:test';
import assert from 'node:assert/strict';
import { BASES, gcd, modPow, modularPermutation, simulatePeriodCircuit, sampleCounts, mulberry32, limitDenominator, inferPeriodFromValue, factorsFromPeriod, runShorSimulation } from '../src/quantum/shor-core.js';

const ORDERS = { 2: 4, 4: 2, 7: 4, 8: 4, 11: 2, 13: 4 };

test('classical helpers match modular arithmetic', () => {
  assert.equal(gcd(12, 15), 3);
  assert.equal(gcd(10, 15), 5);
  for (const a of BASES) assert.equal(modPow(a, ORDERS[a], 15), 1);
  assert.equal(modPow(7, 2, 15), 4);
});

test('compiled permutation follows multiplication by a on the |1> orbit', () => {
  for (const a of BASES) {
    const perm = modularPermutation(a, 1);
    // The compiled SWAP/X network may traverse the subgroup in a different
    // order (little-endian qubit convention), but the orbit from |1> must be
    // exactly the cyclic subgroup generated by a and have the same order.
    const orbit = new Set([1]);
    let y = perm[1];
    while (y !== 1 && orbit.size <= ORDERS[a]) { orbit.add(y); y = perm[y]; }
    assert.equal(y, 1);
    assert.equal(orbit.size, ORDERS[a], `a=${a}`);
    const subgroup = new Set(Array.from({ length: ORDERS[a] }, (_, k) => modPow(a, k + 1, 15)));
    assert.deepEqual(orbit, subgroup, `a=${a}`);
    assert.deepEqual(Array.from(modularPermutation(a, 0)), Array.from({ length: 16 }, (_, i) => i));
  }
  assert.throws(() => modularPermutation(3, 1), /Base must be/);
  assert.throws(() => modularPermutation(7, -1), /nonnegative/);
});

test('statevector distribution is normalized and peaks at s/r for every base', () => {
  for (const a of BASES) {
    const { probabilities, normalization } = simulatePeriodCircuit(a);
    assert.ok(Math.abs(normalization - 1) < 1e-12);
    const sum = probabilities.reduce((x, y) => x + y, 0);
    assert.ok(Math.abs(sum - 1) < 1e-12);
    const order = ORDERS[a];
    for (let value = 0; value < 256; value++) {
      const expected = value % (256 / order) === 0 ? 1 / order : 0;
      assert.ok(Math.abs(probabilities[value] - expected) < 1e-12, `a=${a} value=${value}`);
    }
  }
});

test('sampling is deterministic with a seeded PRNG and respects shot count', () => {
  const { probabilities } = simulatePeriodCircuit(7);
  const a = sampleCounts(probabilities, 128, mulberry32(42));
  const b = sampleCounts(probabilities, 128, mulberry32(42));
  assert.deepEqual(a, b);
  assert.equal(a.samples.length, 128);
  assert.equal(Object.values(a.counts).reduce((x, y) => x + y, 0), 128);
  assert.throws(() => sampleCounts(probabilities, 0, mulberry32(1)), /shots/);
});

test('continued fractions and period validation handle reduced denominators', () => {
  assert.deepEqual(limitDenominator(128, 256, 14), { numerator: 1, denominator: 2 });
  assert.deepEqual(limitDenominator(64, 256, 14), { numerator: 1, denominator: 4 });
  assert.deepEqual(limitDenominator(192, 256, 14), { numerator: 3, denominator: 4 });
  assert.equal(inferPeriodFromValue(64, 7).period, 4);
  const lifted = inferPeriodFromValue(128, 7);
  assert.equal(lifted.candidatePeriod, 2);
  assert.equal(lifted.period, 4);
  assert.equal(lifted.method, 'validated-multiple-x2');
  assert.equal(inferPeriodFromValue(0, 7).period, null);
});

test('factor extraction verifies the cofactor and rejects odd periods', () => {
  for (const a of BASES) {
    const result = factorsFromPeriod(a, ORDERS[a]);
    assert.equal(result.ok, true, `${a}: ${result.detail}`);
    assert.deepEqual(result.factors, [3, 5]);
  }
  assert.equal(factorsFromPeriod(7, 3).reason, 'odd-period');
});

test('full browser hybrid pipeline factors 15 for every fixed base and several seeds', () => {
  for (const a of BASES) {
    for (const seed of [0, 1, 42, 123]) {
      const result = runShorSimulation({ base: a, seed, shots: 8, maxAttempts: 6 });
      assert.equal(result.success, true, `a=${a} seed=${seed}`);
      assert.deepEqual(result.factors, [3, 5]);
      assert.equal(result.backend, 'browser-statevector');
      assert.equal(result.hardware, false);
      assert.equal(result.N, 15);
    }
  }
});

test('auto base mode is reproducible and bounded', () => {
  const a = runShorSimulation({ seed: 7, shots: 4, maxAttempts: 5 });
  const b = runShorSimulation({ seed: 7, shots: 4, maxAttempts: 5 });
  assert.deepEqual(a.events, b.events);
  assert.throws(() => runShorSimulation({ base: 3 }), /Base must be/);
  assert.throws(() => runShorSimulation({ shots: 2000 }), /shots/);
  assert.throws(() => runShorSimulation({ maxAttempts: 11 }), /maxAttempts/);
  assert.throws(() => runShorSimulation({ seed: -1 }), /seed/);
});

test('result contains no wallet/address/key fields', () => {
  const result = runShorSimulation({ base: 7, seed: 42, shots: 1 });
  for (const field of ['privateKey', 'mnemonic', 'address', 'balance', 'publicKey', 'wallet']) assert.equal(field in result, false, field);
  const serialized = JSON.stringify(result);
  for (const word of ['privateKey', 'mnemonic', 'secp256k1', '0x']) assert.equal(serialized.includes(word), false, word);
});
